function detectLang() {
  try {
    var loc = Qt.locale().name || "en";
    var prefix = loc.slice(0, 2).toLowerCase();
    if (strings[prefix]) return prefix;
  } catch (e) {}
  return "en";
}

function tr(key, langOverride) {
  var lang = langOverride || detectLang();
  var dict = strings[lang] || strings.en;
  return dict[key] || (strings.en[key] || key);
}
